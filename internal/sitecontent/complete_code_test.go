func TestCompleteCodeTeachingProtection(t *testing.T) {
	code := "package main\nimport \"fmt\"\nvar message, name, formats string\nfunc main() {\n    // Return a greeting message for name.\n    // Associate message with name.\n    // formats contains greeting formats.\n    // Capture connection properties.\n    // Get a database handle.\n    // Query albums by artist.\n    fmt.Println(\"literal\", message, name, formats, 42)\n    // int\n    // OK\n    // len(x)\n    //go:generate use the tool\n}\n"
	for _, enclosing := range []struct{ name, before, after string }{
		{"x.md", "```go\n", "```\n"},
		{"x.html", "<pre>\n", "</pre>\n"},
		{"x.md", "", ""},
	} {
		t.Run(enclosing.before, func(t *testing.T) {
			body := code
			if enclosing.before == "" {
				body = "    " + strings.ReplaceAll(strings.TrimSuffix(code, "\n"), "\n", "\n    ") + "\n"
			}
			d, raw := formalFixture(t, enclosing.name, "# Teaching\n"+enclosing.before+body+enclosing.after)
			values := []string{}
			count := 0
			for _, s := range d.Slots {
				values = append(values, s.Source)
				if !strings.Contains(s.Locator, "#teaching-comment:") {
					continue
				}
				count++
				if strings.Contains(s.Source, "Associate") {
					if len(s.Protected) != 2 {
						t.Fatal(s)
					}
					// Chinese word order reverses the source identifier order.
					values[len(values)-1] = "将" + s.Protected[1].Token + "与" + s.Protected[0].Token + "关联。"
				}
			}
			if count != 6 {
				t.Fatalf("safe comments=%d", count)
			}
			target := formalTarget(d, values)
			got := checkFormal(t, d, raw, target, true)
			if !bytes.Contains(got, []byte("// 将name与message关联。")) {
				t.Fatal(string(got))
			}
			for _, static := range []string{"// int", "// OK", "// len(x)", "//go:generate use the tool", "fmt.Println(\"literal\", message, name, formats, 42)"} {
				if !bytes.Contains(got, []byte(static)) {
					t.Fatal("machine bytes changed", static)
				}
			}
			for _, p := range d.Units[0].Protected {
				// Rewriting any opaque boundary/identifier is rejected.
				checkFormal(t, d, raw, strings.Replace(target, p.Token, p.Raw+"changed", 1), false)
			}
			for _, mutation := range [][2]string{
				{"package main", "package changed"}, {"import \"fmt\"", "import \"os\""},
				{"func main()", "func changed()"}, {"fmt.Println", "fmt.Print"},
				{"\"literal\"", "\"changed\""}, {"42", "43"},
				{"// ", "/ "}, {"// int", ""}, {"// int", "// int\n// added"},
				{"\n", " "}, {"    ", " "}, {"{", "["},
				{"```go", "```text"}, {"<pre>", "<code>"}, {"</pre>", "</code>"},
			} {
				for _, p := range d.Units[0].Protected {
					if p.Role != "boundary" || !strings.Contains(p.Raw, mutation[0]) {
						continue
					}
					changed := strings.Replace(p.Raw, mutation[0], mutation[1], 1)
					checkFormal(t, d, raw, strings.Replace(target, p.Token, changed, 1), false)
				}
			}
			for i, s := range d.Slots {
				if !strings.Contains(s.Source, "Associate") {
					continue
				}
				for _, bad := range []string{
					"译文\n", "译文 // added", "译文 /* block */", "",
					s.Protected[0].Token + "X " + s.Protected[1].Token,
					s.Protected[0].Token + " " + s.Protected[1].Token + " formats",
					s.Protected[0].Token + " " + s.Protected[1].Token + " name",
					s.Protected[0].Token + " " + s.Protected[1].Token + " newName",
					s.Protected[0].Token + " " + s.Protected[1].Token + " new_identifier",
					s.Protected[0].Token + " " + s.Protected[1].Token + " unknown()",
				} {
					v := append([]string{}, values...)
					v[i] = bad
					checkFormal(t, d, raw, formalTarget(d, v), false)
				}
			}
		})
	}
}

func TestCompleteCodeUnsafeFragments(t *testing.T) {
	for _, code := range []string{
		"func main() {\n // Teaching prose for the reader.\n /* block comment */\n}\n",
		"unknown ???\n// Teaching prose for the reader.\n",
		"// int\n// OK\n// len(x)\n",
		"package main\n//go:generate use the tool\n//line file.go:1\n// +build use the tool\n// Output: the expected value\n// Unordered output: the expected value\n// Code generated by the tool. DO NOT EDIT.\nfunc main() {}\n",
	} {
		d, _ := formalFixture(t, "x.md", "# Teaching\n\n```go\n"+code+"```\n")
		for _, s := range d.Slots {
			if strings.Contains(s.Locator, "teaching-comment") {
				t.Fatal("unsafe exposed", s)
			}
		}
	}
}

func TestCompleteCodeUnicodeIdentifierBinding(t *testing.T) {
	d, raw := formalFixture(t, "x.md", "```go\nvar 名称 string\nfunc main() {\n // Return a greeting for 名称.\n}\n```\n")
	if len(d.Slots) != 1 || len(d.Slots[0].Protected) != 1 {
		t.Fatal(d.Slots)
	}
	target := formalTarget(d, []string{"为" + d.Slots[0].Protected[0].Token + "返回问候语。"})
	checkFormal(t, d, raw, target, true)
	checkFormal(t, d, raw, strings.Replace(target, d.Slots[0].Protected[0].Token, "另一个名称", 1), false)
}

// Completeness invariant: every safe natural-language coordinate discovered
// by the shared analyzer is covered by a formal slot, never by boundary raw.
func TestCompleteCodeFrozenCompleteness(t *testing.T) {
	root := repositoryRoot(t)
	g, err := LoadCurrent(root)
	if err != nil {
		t.Fatal(err)
	}
	docs, raw, err := WorkflowDocuments(root, g, "learn-docs-v1")
	if err != nil {
		t.Fatal(err)
	}
	needles := map[int][]string{
		6:  {"Capture connection properties.", "Get a database handle.", "albumsByArtist queries", "Hard-code ID 2", "addAlbum adds"},
		7:  {"Use f.Add to provide a seed corpus"},
		8:  {"Initialize a map", "SumInts adds", "SumIntsOrFloats sums", "SumNumbers sums"},
		18: {"album represents", "getAlbums responds", "postAlbums adds", "Call BindJSON", "getAlbumByID locates"},
	}
	for _, d := range docs {
		b := raw[d.Path]
		got, err := ReconstructWorkflow(d, b, map[string]string{d.Units[0].ID: d.Units[0].Source})
		if err != nil || !bytes.Equal(got, b) {
			t.Fatalf("frozen source roundtrip %s: %v", d.Path, err)
		}
		offset, err := parseMetadata(b, func(int, int, string) {})
		if err != nil {
			t.Fatal(err)
		}
		count := 0
		err = teachingSpans(b[offset:], offset, strings.HasSuffix(d.Path, ".md"), func(a, z int, _ string) {
			found := false
			for _, s := range d.Slots {
				if s.Start <= a && s.End >= z {
					found = true
				}
			}
			if !found {
				t.Errorf("safe body lost: %s %d:%d", d.Path, a, z)
			}
			count++
		}, nil)
		if err != nil {
			t.Fatal(err)
		}
		for _, needle := range needles[d.StableIndex] {
			found := false
			for _, s := range d.Slots {
				if strings.Contains(string(b[s.Start:s.End]), needle) {
					found = true
				}
			}
			if !found {
				t.Fatal("real teaching comment not open", d.Path, needle)
			}
			for _, p := range d.Units[0].Protected {
				if p.Role == "boundary" && strings.Contains(p.Raw, needle) {
					t.Fatal("teaching comment swallowed", d.Path)
				}
			}
		}
		t.Logf("index=%d safe comments=%d %s", d.StableIndex, count, d.Path)
	}
	// Check the original natural-language helper as well as complete bodies.
	code := "package main\nfunc main() {\n // Create a Context with a timeout.\n Context()\n}\n"
	d, _ := formalFixture(t, "x.md", "```go\n"+code+"```\n")
	for _, s := range i18n.SafeTeachingCommentSpans(code) {
		found := false
		for _, slot := range d.Slots {
			if slot.Start <= len("```go\n")+s.Start && slot.End >= len("```go\n")+s.End {
				found = true
			}
		}
		if !found {
			t.Fatal("safe teaching span lost", s)
		}
	}
}
