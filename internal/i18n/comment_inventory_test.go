func TestCommentInventoryClassificationAndStrings(t *testing.T) {
	static := AnalyzeCommentCode("var b []int\nfmt.Println(len(b),cap(b)) // len(b)=0, cap(b)=5\n", "go", "block/1", false)
	if len(static.Comments) != 1 || static.Comments[0].Kind != "non-language/structural-comment" {
		t.Fatal(static)
	}
	commentedCode := AnalyzeCommentCode("package p\nfunc f(){\n// message := fmt.Sprintf(randomFormat(), name)\n}\n", "go", "block/1", false)
	if commentedCode.Comments[0].Kind != "non-language/structural-comment" {
		t.Fatal(commentedCode)
	}
	code := "package p\n//go:build linux\n//go:generate tool\n//line x.go:1\n// +build linux\n// Code generated by tool. DO NOT EDIT.\n// START OMIT\n// Output: value\n// Return the vulnerability ID.\nvar s = `// not a comment`\n"
	b := AnalyzeCommentCode(code, "go", "code/1", false)
	if b.Unsupported || len(b.Comments) != 8 {
		t.Fatalf("%+v", b)
	}
	for _, c := range b.Comments[:7] {
		if c.Kind != "machine-semantic-comment" || c.Policy != "protected" {
			t.Fatal(c)
		}
	}
	if b.Comments[7].Kind != "teaching-comment" {
		t.Fatal(b.Comments[7])
	}
	for _, lang := range []string{"shell", "yaml", "sql", "unknown"} {
		b := AnalyzeCommentCode("// Do not guess syntax.", lang, "block/1", false)
		if !b.Unsupported || len(b.Comments) != 0 {
			t.Fatal(b)
		}
	}
	// A machine-looking Go directive in a JSON schema has no Go semantics.
	b = AnalyzeCommentCode("{ //go:generate tool\n\"path\": string }", "json", "block/1", false)
	if b.Unsupported || b.Comments[0].Kind != "unclassified" {
		t.Fatal(b)
	}
	r, f := CompareCommentBlocks("x", "zh", []CommentCodeBlock{b}, []CommentCodeBlock{b})
	if ValidateCommentCoverage(r, f, false) == nil {
		t.Fatal("unclassified accepted")
	}
}

func TestCommentInventoryCorrespondenceAndLocalePolicy(t *testing.T) {
	source := "package p\n// Return the vulnerability ID.\nvar id = 1\n//go:generate tool\n"
	s := AnalyzeCommentCode(source, "go", "example/1", true)
	compare := func(target, base string) ([]CommentSlotComparison, []string) {
		b := AnalyzeCommentCode(target, "go", "example/1", true)
		return CompareCommentBlocks("package/path/example/id", base, []CommentCodeBlock{s}, []CommentCodeBlock{b})
	}
	r, f := compare(source, "zh")
	if !r[0].ExactSourceCarry || !r[0].ReviewRequired || ValidateCommentCoverage(r, f, true) == nil {
		t.Fatal(r, f)
	}
	for _, locale := range []string{"en-GB", "en-CA", "en-AU", "en-SG", "en-ZA", "en-IN", "en-NZ"} {
		base, err := CommentBaseLanguage(locale)
		if err != nil {
			t.Fatal(err)
		}
		r, f = compare(source, base)
		if r[0].ReviewRequired || ValidateCommentCoverage(r, f, true) != nil {
			t.Fatal(locale, r, f)
		}
	}
	r, f = compare(strings.Replace(source, "Return the vulnerability ID.", "返回 vulnerability ID。", 1), "zh")
	if !r[0].StructureMatch || r[0].ReviewRequired || ValidateCommentCoverage(r, f, true) != nil {
		t.Fatal(r, f)
	}
	for _, target := range []string{strings.Replace(source, "// Return the vulnerability ID.\n", "", 1), strings.Replace(source, "var id", "// Extra comment here.\nvar id", 1), strings.Replace(source, "//go:generate tool", "//go:generate changed", 1), strings.Replace(source, "var id = 1", "var changed = 1", 1)} {
		r, f = compare(target, "zh")
		if ValidateCommentCoverage(r, f, false) == nil {
			t.Fatal("mutation accepted", target, r, f)
		}
	}
	// Identity is structural, not a source line or byte offset.
	shifted := AnalyzeCommentCode("\n\n"+source, "go", "example/1", true)
	r1, _ := CompareCommentBlocks("x", "en", []CommentCodeBlock{s}, []CommentCodeBlock{s})
	r2, _ := CompareCommentBlocks("x", "en", []CommentCodeBlock{shifted}, []CommentCodeBlock{shifted})
	if r1[0].SlotID != r2[0].SlotID {
		t.Fatal(r1, r2)
	}
	a, _ := json.Marshal(r1)
	b, _ := json.Marshal(r1)
	if string(a) != string(b) {
		t.Fatal("nondeterministic")
	}
}

func TestCommentInventoryTourRealPageAndExample(t *testing.T) {
	c, err := BuildCatalog(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	p, err := c.Page("concurrency/2")
	if err != nil {
		t.Fatal(err)
	}
	blocks := TourPageCommentBlocks(p.Source)
	teaching := 0
	for _, b := range blocks {
		for _, s := range b.Comments {
			if s.Kind == "teaching-comment" {
				teaching++
			}
		}
	}
	if teaching == 0 {
		t.Fatal("Tour Page comments omitted")
	}
	static, err := c.Page("moretypes/13")
	if err != nil {
		t.Fatal(err)
	}
	for _, b := range TourPageCommentBlocks(static.Source) {
		for _, s := range b.Comments {
			if s.Kind != "non-language/structural-comment" {
				t.Fatal("static annotations misclassified", s)
			}
		}
	}
	for _, e := range c.Examples {
		if !e.EligibleTranslation {
			continue
		}
		b := AnalyzeCommentCode(string(e.Source), "go", "example/1", true)
		if b.Unsupported || len(b.Comments) == 0 {
			t.Fatal(e.ID, b)
		}
	}
}

func TestCommentCurrentTargetRejectsDrift(t *testing.T) {
	root, c, _, snapshot := checkpointFixture(t)
	if _, _, err := EstablishCurrentTranslationAuthorization(root, c, "zh-CN", snapshot); err != nil {
		t.Fatal(err)
	}
	rows, _, err := CurrentAcceptedCommentTargets(root, c, "zh-CN")
	if err != nil || len(rows) != 3 {
		t.Fatal(rows, err)
	}
	if err := os.WriteFile(filepath.Join(root, rows[0].Candidate.Path), []byte("stale"), 0600); err != nil {
		t.Fatal(err)
	}
	if _, _, err := CurrentAcceptedCommentTargets(root, c, "zh-CN"); err == nil {
		t.Fatal("stale accepted bytes authorized")
	}
}
