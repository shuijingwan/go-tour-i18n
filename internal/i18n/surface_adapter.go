package i18n

import (
	"fmt"
	"os"
	"path/filepath"
)

// TranslationUnitAdapter supplies only source/protection/structure behavior.
// Processing, attempts, evidence, Snapshot and QC remain in the shared lifecycle.
type TranslationUnitAdapter interface {
	ProtectedInput(*Glossary) (string, []string, error)
	Restore(string) ([]byte, error)
	Validate([]byte, *Glossary) error
}

// ArchivedGenerationAdapter decodes a historical formal representation; it
// does not own recovery, attempts or acceptance. The returned raw bytes must
// match the immutable original invocation and this exact current input.
type ArchivedGenerationAdapter interface {
	VerifyGenerationOrigin(string, string, TranslationUnitGenerationOrigin, []byte) error
}

// FrozenGenerationAdapter verifies the original invocation, including its
// archived glossary, without confusing it with today's Generation eligibility.
type FrozenGenerationAdapter interface {
	VerifyFrozenGenerationOrigin(string, string, TranslationUnitGenerationOrigin, []byte) error
}

// An additive binding in the existing batch manifest, not a receipt or a new
// invocation. Original transport bytes retain their actual scope and identity.
type TranslationUnitGenerationOrigin struct {
	Bundle GlossaryArchiveReference `json:"bundle"`
	Result GlossaryArchiveReference `json:"result"`
}

func verifyGenerationOrigin(root, locale string, unit *TranslationUnit, record RetranslationBatchUnit, raw []byte) error {
	if record.GenerationOrigin == nil {
		return nil
	}
	a, ok := unit.Adapter.(ArchivedGenerationAdapter)
	if !ok {
		return fmt.Errorf("%s: unsupported archived formal representation", unit.ID)
	}
	return a.VerifyGenerationOrigin(root, locale, *record.GenerationOrigin, raw)
}

// LandExistingGenerationBatch installs exact, already generated bytes against
// an exported shared manifest. It creates no Generation Bundle and makes no
// claim that the new mechanical manifest was the model's original input.
func LandExistingGenerationBatch(root string, catalog *Catalog, locale, batchID string, origins map[string]TranslationUnitGenerationOrigin, outputs map[string][]byte) error {
	dir := filepath.Join(root, "data", "retranslation-runs", locale, batchID)
	m, err := readRetranslationProcessManifest(dir, locale, batchID)
	if err != nil {
		return err
	}
	if len(origins) != m.UnitCount || len(outputs) != m.UnitCount {
		return fmt.Errorf("existing generation exact-set mismatch")
	}
	if err := ensureNoGenerationImportPending(dir); err != nil {
		return err
	}
	if _, err := os.Lstat(filepath.Join(dir, "raw-responses")); !os.IsNotExist(err) {
		return fmt.Errorf("formal outputs already exist or cannot be inspected")
	}
	for i := range m.Units {
		r := &m.Units[i]
		u, err := catalog.Unit(r.UnitID)
		if err != nil {
			return err
		}
		origin, ok := origins[r.UnitID]
		if !ok {
			return fmt.Errorf("missing original invocation: %s", r.UnitID)
		}
		if r.GenerationOrigin != nil && *r.GenerationOrigin != origin {
			return fmt.Errorf("refuse original invocation binding overwrite")
		}
		r.GenerationOrigin = &origin
		raw, ok := outputs[r.UnitID]
		if !ok {
			return fmt.Errorf("missing original output: %s", r.UnitID)
		}
		if err := validateGenerationOutputBytes(raw); err != nil {
			return err
		}
		if err := verifyGenerationOrigin(root, locale, u, *r, raw); err != nil {
			return err
		}
	}
	// Persist the original invocation bindings before installation. A failure
	// leaves a manifest-only export; no partial formal output is exposed.
	if err := writeTranslationJSON(filepath.Join(dir, "manifest.json"), m); err != nil {
		return err
	}
	stage, err := os.MkdirTemp(dir, ".existing-generation-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	for _, r := range m.Units {
		if err := writeNewGenerationFile(filepath.Join(stage, filepath.Base(r.InputPath)), outputs[r.UnitID]); err != nil {
			return err
		}
	}
	return renameGenerationDirNoReplace(stage, filepath.Join(dir, "raw-responses"))
}

type AdaptedTranslationUnit struct {
	Unit        TranslationUnit
	Adapter     TranslationUnitAdapter
	StableIndex int
	Route       string
	// WorkingSet and WorkingSetLimit describe initial scheduling only.
	// They are not TranslationUnit identity or revision partitions.
	WorkingSet      string
	WorkingSetLimit int
}

// RequireTranslationInvocation applies the shared boundary to later revision
// and re-QC work without inheriting initial batch membership.
func (c *Catalog) RequireTranslationInvocation(ids []string) error {
	if len(ids) > MaxRetranslationExportLimit {
		return fmt.Errorf("独立 invocation 超过共享上限：%d", MaxRetranslationExportLimit)
	}
	var kind UnitKind
	for _, id := range ids {
		u, err := c.Unit(id)
		if err != nil {
			return err
		}
		if kind != "" && kind != u.Kind {
			return fmt.Errorf("独立 invocation 不得混合 Page 与 Example")
		}
		kind = u.Kind
	}
	return nil
}

func (c *Catalog) RequireInitialTranslationWorkingSet(ids []string) error {
	if err := c.RequireTranslationInvocation(ids); err != nil {
		return err
	}
	group := ""
	for _, id := range ids {
		for _, u := range c.Adapted {
			if u.Unit.ID != id {
				continue
			}
			if u.WorkingSet != "" && group != "" && group != u.WorkingSet {
				return fmt.Errorf("独立 invocation 不得合并固定页面批次")
			}
			group = u.WorkingSet
			if u.WorkingSetLimit > 0 && len(ids) > u.WorkingSetLimit {
				return fmt.Errorf("独立 invocation 超过固定页面批次上限：%d", u.WorkingSetLimit)
			}
		}
	}
	return nil
}

// UseTranslationUnitScope selects a complete content scope for Snapshot/QC.
// The full catalog remains available for immutable historical batch lookup.
func (c *Catalog) UseTranslationUnitScope(ids []string) error {
	seen := map[string]bool{}
	for _, id := range ids {
		if _, err := c.Unit(id); err != nil {
			return err
		}
		if seen[id] {
			return fmt.Errorf("duplicate translation scope: %s", id)
		}
		seen[id] = true
	}
	if len(ids) == 0 {
		return fmt.Errorf("empty translation scope")
	}
	c.TranslationScope = append([]string(nil), ids...)
	return nil
}

func (c *Catalog) inTranslationScope(id string) bool {
	if len(c.TranslationScope) == 0 {
		return true
	}
	for _, v := range c.TranslationScope {
		if v == id {
			return true
		}
	}
	return false
}
