package main

import (
	"fmt"
)

type Fetcher interface {
	// Fetch mengembalikan kandungan URL dan
	// hirisan URL yang ditemui pada halaman itu.
	Fetch(url string) (body string, urls []string, err error)
}

// Crawl menggunakan fetcher untuk merangkak secara rekursif
// halaman bermula dengan url, sehingga kedalaman maksimum depth.
func Crawl(url string, depth int, fetcher Fetcher) {
	// TODO: Ambil URL secara selari.
	// TODO: Jangan ambil URL yang sama dua kali.
	// Pelaksanaan ini tidak melakukan kedua-duanya:
	if depth <= 0 {
		return
	}
	body, urls, err := fetcher.Fetch(url)
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Printf("found: %s %q\n", url, body)
	for _, u := range urls {
		Crawl(u, depth-1, fetcher)
	}
	return
}

func main() {
	Crawl("https://golang.org/", 4, fetcher)
}

