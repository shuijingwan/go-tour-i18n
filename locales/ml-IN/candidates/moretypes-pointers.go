package main

import "fmt"

func main() {
	i, j := 42, 2701

	p := &i         // i-ലേക്ക് പോയിന്റ് ചെയ്യുക
	fmt.Println(*p) // പോയിന്റർ വഴി i വായിക്കുക
	*p = 21         // പോയിന്റർ വഴി i-യുടെ മൂല്യം മാറ്റുക
	fmt.Println(i)  // i-യുടെ പുതിയ മൂല്യം കാണുക

	p = &j         // j-ലേക്ക് പോയിന്റ് ചെയ്യുക
	*p = *p / 37   // പോയിന്റർ വഴി j-യെ ഹരിക്കുക
	fmt.Println(j) // j-യുടെ പുതിയ മൂല്യം കാണുക
}
