package main

import "fmt"

func main() {
	i, j := 42, 2701

	p := &i         // створити вказівник на i
	fmt.Println(*p) // прочитати i через вказівник
	*p = 21         // задати значення i через вказівник
	fmt.Println(i)  // переглянути нове значення i

	p = &j         // створити вказівник на j
	*p = *p / 37   // поділити j через вказівник
	fmt.Println(j) // переглянути нове значення j
}
