package main

import (
	"fmt"
)

type Fetcher interface {
	// Fetch renvoie le corps de l’URL et
	// un slice contenant les URL trouvées sur cette page.
	Fetch(url string) (body string, urls []string, err error)
}

// Crawl utilise fetcher pour explorer récursivement
// les pages à partir de url, jusqu’à la profondeur maximale depth.
func Crawl(url string, depth int, fetcher Fetcher) {
	// TODO: récupérer les URL en parallèle.
	// TODO: ne pas récupérer deux fois la même URL.
	// Cette implémentation ne fait ni l’un ni l’autre :
	if depth <= 0 {
		return
	}
	body, urls, err := fetcher.Fetch(url)
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Printf("found: %s %q\n", url, body)
	for _, u := range urls {
		Crawl(u, depth-1, fetcher)
	}
	return
}

func main() {
	Crawl("https://golang.org/", 4, fetcher)
}

