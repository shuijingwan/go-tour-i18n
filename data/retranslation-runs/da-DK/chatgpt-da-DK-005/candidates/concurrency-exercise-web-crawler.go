package main

import (
	"fmt"
)

type Fetcher interface {
	// Fetch returnerer indholdet af den webside, som URL henviser til, samt
	// en slice med de URL’er, der findes på siden.
	Fetch(url string) (body string, urls []string, err error)
}

// Crawl bruger fetcher til at gennemgå
// sider rekursivt fra url med depth som maksimal dybde.
func Crawl(url string, depth int, fetcher Fetcher) {
	// TODO: Hent URL’er parallelt.
	// TODO: Hent ikke den samme URL to gange.
	// Denne implementering gør ingen af delene:
	if depth <= 0 {
		return
	}
	body, urls, err := fetcher.Fetch(url)
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Printf("found: %s %q\n", url, body)
	for _, u := range urls {
		Crawl(u, depth-1, fetcher)
	}
	return
}

func main() {
	Crawl("https://golang.org/", 4, fetcher)
}

