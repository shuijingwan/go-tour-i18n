package main

import "fmt"

func main() {
	i, j := 42, 2701

	p := &i         // създаваме указател към i
	fmt.Println(*p) // прочитаме i чрез указателя
	*p = 21         // задаваме стойност на i чрез указателя
	fmt.Println(i)  // виждаме новата стойност на i

	p = &j         // пренасочваме указателя p към j
	*p = *p / 37   // делим j чрез указателя
	fmt.Println(j) // виждаме новата стойност на j
}
