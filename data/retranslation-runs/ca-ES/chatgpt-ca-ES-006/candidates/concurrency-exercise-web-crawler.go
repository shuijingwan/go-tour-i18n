package main

import (
	"fmt"
)

type Fetcher interface {
	// Fetch retorna el cos de URL i
	// un slice de URLs trobats en aquesta pàgina.
	Fetch(url string) (body string, urls []string, err error)
}

// Crawl utilitza fetcher per rastrejar recursivament
// pàgines a partir de l'url, fins a una profunditat màxima de depth.
func Crawl(url string, depth int, fetcher Fetcher) {
	// TODO: Obté URLs en paral·lel.
	// TODO: No obtinguis el mateix URL dues vegades.
	// Aquesta implementació no fa cap de les dues coses:
	if depth <= 0 {
		return
	}
	body, urls, err := fetcher.Fetch(url)
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Printf("found: %s %q\n", url, body)
	for _, u := range urls {
		Crawl(u, depth-1, fetcher)
	}
	return
}

func main() {
	Crawl("https://golang.org/", 4, fetcher)
}

// fakeFetcher és un Fetcher que retorna resultats predefinits.
type fakeFetcher map[string]*fakeResult

