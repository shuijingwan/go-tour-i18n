type Fetcher interface {
	// Fetch returnează conținutul paginii asociate cu URL-ul respectiv și
	// un slice de URL-uri găsite pe pagina respectivă.
	Fetch(url string) (body string, urls []string, err error)
}

// Crawl folosește fetcher pentru a parcurge recursiv
// paginile începând de la url, până la adâncimea maximă indicată de depth.
func Crawl(url string, depth int, fetcher Fetcher) {
	// TODO: Preia URL-urile în paralel.
	// TODO: Nu prelua același URL de două ori.
	// Această implementare nu face niciuna dintre acestea:
	if depth <= 0 {
		return
	}
	body, urls, err := fetcher.Fetch(url)
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Printf("found: %s %q\n", url, body)
	for _, u := range urls {
		Crawl(u, depth-1, fetcher)
	}
	return
}

func main() {
	Crawl("https://golang.org/", 4, fetcher)
}

// fakeFetcher este un Fetcher care returnează rezultate prestabilite.
