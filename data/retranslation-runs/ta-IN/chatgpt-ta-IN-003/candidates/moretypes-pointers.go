package main

import "fmt"

func main() {
	i, j := 42, 2701

	p := &i         // i-ஐச் சுட்டுக
	fmt.Println(*p) // சுட்டி வழியாக i-ஐ வாசிக்கவும்
	*p = 21         // சுட்டி வழியாக i-ஐ அமைக்கவும்
	fmt.Println(i)  // i-ன் புதிய மதிப்பைப் பார்க்கவும்

	p = &j         // j-ஐச் சுட்டுக
	*p = *p / 37   // சுட்டி வழியாக j-ஐ வகுக்கவும்
	fmt.Println(j) // j-ன் புதிய மதிப்பைப் பார்க்கவும்
}
